"""Native Maya ASCII animation with exact integer frame keys, no FBX tick drift."""
import json
import re
from pathlib import Path


def time_unit(fps):
    if fps <= 0:
        raise ValueError('FPS must be positive')
    for rate, unit in ((24000/1001,'23.976fps'),(30000/1001,'29.97fps'),(60000/1001,'59.94fps')):
        if abs(fps-rate)<.0001:
            return unit
    return {24: 'film', 25: 'pal', 30: 'ntsc', 48: 'show', 50: 'palf', 60: 'ntscf'}.get(fps, f'{fps:.12g}fps')


def rig_joint_pairs(source, target):
    """Match anatomical phalanges, including SOMA's extra metacarpal joint."""
    pairs = []
    for name, joint in target.items():
        source_name = name
        # SOMA has metacarpal + three phalanges + tip; Mixamo has
        # three phalanges + tip. Equal suffixes are not equal anatomy.
        match = re.fullmatch(r'(Left|Right)Hand(Index|Middle|Ring|Pinky)([1-4])', name)
        if match:
            side, finger, number = match.groups()
            stem = side + 'Hand' + finger
            if stem + '4' in source and stem + 'End' in source:
                source_name = stem + (str(int(number)+1) if number != '4' else 'End')
        thumb = re.fullmatch(r'(Left|Right)HandThumb4', name)
        if thumb and thumb.group(1) + 'HandThumbEnd' in source:
            source_name = thumb.group(1) + 'HandThumbEnd'
        if source_name in source:
            pairs.append((source[source_name], joint))
    return pairs


def write(path, root, frames, fps):
    lines = ['//Maya ASCII 2026 scene', '//Generated by MoCapGate, CYBER Department',
             'requires maya "2026";', f'currentUnit -l centimeter -a degree -t {time_unit(fps)};']
    joints = []
    def walk(joint, parent=None):
        name = re.sub(r'[^A-Za-z0-9_]', '_', joint.name.split(':')[-1])
        joints.append((joint, name))
        lines.append(f'createNode joint -n "{name}"' + (f' -p "{parent}"' if parent else '') + ';')
        lines.append('setAttr ".t" -type "double3" ' + ' '.join(map(str, joint.offset)) + ';')
        lines.append('setAttr ".ro" 4;')  # Maya YXZ row order matches BVH ZXY column order
        for child in joint.children:
            walk(child, name)
    walk(root)
    for joint, name in joints:
        moves = joint is root or any('pos' in frame.get(joint.name, {}) for frame in frames[:1])  # Hips под костью Root
        for attr, index in [('rz', 0), ('rx', 1), ('ry', 2)] + ([('tx', 0), ('ty', 1), ('tz', 2)] if moves else []):
            translation = attr.startswith('t')
            values = [frame.get(joint.name, {}).get('pos' if translation else 'rot', (0, 0, 0))[index] for frame in frames]
            curve = name + '_' + attr
            lines += [f'createNode animCurveT{"L" if translation else "A"} -n "{curve}";', 'setAttr ".tan" 2;',
                      f'setAttr -s {len(values)} ".ktv[0:{len(values)-1}]" ' + ' '.join(f'{i+1} {v:.12g}' for i,v in enumerate(values)) + ';',
                      f'connectAttr "{curve}.o" "{name}.{attr}";']
    lines.append(f'playbackOptions -min 1 -max {len(frames)} -ast 1 -aet {len(frames)};')
    Path(path).write_text('\n'.join(lines) + '\n', encoding='utf-8')


def append_audio(path, wav, node='MoCapGateAudio'):
    """Звук съёмки в сцене Maya: узел audio с началом на кадре 1 (как первый кадр анимации). Повторно не добавляет."""
    path = Path(path)
    text = path.read_text(encoding='utf-8')
    if f'createNode audio -n "{node}"' in text:
        return False
    wav = str(Path(wav).resolve()).replace('\\', '/')
    path.write_text(text.rstrip('\n') + f'\ncreateNode audio -n "{node}";\nsetAttr ".o" 1;\nsetAttr ".f" -type "string" "{wav}";\n',
                    encoding='utf-8')
    return True


def append_camera(path, camera_file, node='CaptureCamera'):
    """Камера съёмки (mocapgate.camera/1) в сцене Maya: положение в см, поворот XYZ, фокус на 35-мм кадре."""
    import json
    import math
    path = Path(path)
    text = path.read_text(encoding='utf-8')
    if f'createNode transform -n "{node}"' in text:
        return False
    cam = json.loads(Path(camera_file).read_text(encoding='utf-8'))
    w, x, y, z = cam['rotation_quat']
    m = [[1 - 2*(y*y + z*z), 2*(x*y - w*z), 2*(x*z + w*y)],
         [2*(x*y + w*z), 1 - 2*(x*x + z*z), 2*(y*z - w*x)],
         [2*(x*z - w*y), 2*(y*z + w*x), 1 - 2*(x*x + y*y)]]
    # порядок вращения Maya xyz: R = Rz·Ry·Rx
    ry = math.degrees(math.asin(max(-1.0, min(1.0, -m[2][0]))))
    rx = math.degrees(math.atan2(m[2][1], m[2][2]))
    rz = math.degrees(math.atan2(m[1][0], m[0][0]))
    px, py, pz = cam.get('position_bvh_cm') or [v * 100 for v in cam['position']]
    aspect = cam['height'] / cam['width']
    lines = [f'createNode transform -n "{node}";', f'setAttr ".t" -type "double3" {px:.6g} {py:.6g} {pz:.6g};',
             f'setAttr ".r" -type "double3" {rx:.6g} {ry:.6g} {rz:.6g};',
             f'createNode camera -n "{node}Shape" -p "{node}";', f'setAttr ".fl" {cam["focal_mm"]:.6g};',
             f'setAttr ".hfa" {36 / 25.4:.6g};', f'setAttr ".vfa" {36 * aspect / 25.4:.6g};', 'setAttr ".ff" 1;']
    path.write_text(text.rstrip('\n') + '\n' + '\n'.join(lines) + '\n', encoding='utf-8')
    return True


def repair_key_times(source, destination, tolerance=.01):
    """Snap only numerical drift; preserve intentional subframe keys and values."""
    text = Path(source).read_text(encoding='utf-8')
    changed = 0
    def fix(match):
        nonlocal changed
        tokens = match[2].split()
        for i in range(0, len(tokens), 2):
            value = float(tokens[i]); rounded = round(value)
            if abs(value-rounded) <= tolerance and value != rounded:
                tokens[i] = str(rounded); changed += 1
        return match[1] + ' '.join(tokens) + ';'
    text = re.sub(r'(setAttr\s+"\.ktv\[[^\]]+\]"\s+)([^;]+);', fix, text)
    Path(destination).write_text(text, encoding='utf-8')
    return changed
